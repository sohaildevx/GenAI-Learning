import streamlit as st
from langchain_groq import ChatGroq
from dotenv import load_dotenv
from langchain.agents import create_agent
from langchain.tools import tool
from langchain_community.utilities import GoogleSerperAPIWrapper
from langgraph.checkpoint.memory import MemorySaver

load_dotenv()

llm_model = ChatGroq(model="openai/gpt-oss-20b", streaming=True)

search = GoogleSerperAPIWrapper()
tools = [search.run]

if "memory" not in st.session_state:
   st.session_state.memory = MemorySaver()
   st.session_state.history = []


agent = create_agent(
    model=llm_model,
    tools=tools,
    checkpointer=st.session_state.memory,
    system_prompt="You are a amazing ai agent and can search on google as well"
)

st.subheader("☁️ Quick Question & Answer With help of AI")

for message in st.session_state.history:
    role = message["role"]
    content = message["content"]
    st.chat_message(role).markdown(content)



query = st.chat_input("Ask Anything")

if query:
    
    st.chat_message("user").markdown(query)
    st.session_state.history.append({"role":"user","content":query})

    # if query.lower() not in ["bye","exit","end"]:
    #   st.chat_message("ai").markdown("GoodBye")
    #   break

    response = agent.stream(
        {"messages": [{"role": "user", "content": query}]},
        {"configurable": {"thread_id": "1"}},
        stream_mode="messages",
    )

    answer = ""
    with st.chat_message("assistant"):
        answer_placeholder = st.empty()

        for message_chunk, metadata in response:
            # Only display tokens generated by the model, not tool output.
            if metadata.get("langgraph_node") != "model":
                continue

            content = message_chunk.content
            if isinstance(content, str):
                answer += content
            elif isinstance(content, list):
                answer += "".join(
                    block.get("text", "")
                    for block in content
                    if isinstance(block, dict)
                )

            answer_placeholder.markdown(answer)

    st.session_state.history.append({"role": "assistant", "content": answer})